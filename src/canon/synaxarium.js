/**
 * Returns the synaxarium entry for the given Ethiopian day (1-30).
 */
export function getSynaxariumEntry(ethDay) {
  const dayNum = parseInt(ethDay, 10);
  return SYNAXARIUM_COMMEMORATIONS[dayNum] || null;
}

/**
 * Searches the synaxarium for commemorations by keyword.
 */
export function searchSynaxarium(query = '') {
  if (!query) return Object.values(SYNAXARIUM_COMMEMORATIONS);
  const q = query.toLowerCase().trim();
  return Object.values(SYNAXARIUM_COMMEMORATIONS).filter(s =>
    s.saint.includes(q) ||
    s.saintEnglish.toLowerCase().includes(q) ||
    s.category.toLowerCase().includes(q) ||
    s.synaxariumExcerpt.includes(q) ||
    s.spiritualLesson.includes(q)
  );
}

/**
 * Returns all 30 synaxarium commemorations as an array.
 */
export function getAllSynaxariumEntries() {
  return Object.entries(SYNAXARIUM_COMMEMORATIONS).map(([day, data]) => ({
    day: parseInt(day, 10),
    ...data
  }));
}
