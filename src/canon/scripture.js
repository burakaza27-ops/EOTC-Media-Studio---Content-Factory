/**
 * Returns a verified scripture matching a theme, mood, or keyword,
 * or falls back to a deterministic, zero-hallucination canonical pick.
 */
export function getVerifiedVerse(themeOrMood = '', keyword = '') {
  const qTheme = (themeOrMood || '').toLowerCase();
  const qKey = (keyword || '').toLowerCase();

  // 1. Try to find a precise match
  const matches = VERIFIED_SCRIPTURES.filter(s => {
    if (qTheme && (s.theme.toLowerCase().includes(qTheme) || qTheme.includes(s.theme.toLowerCase()))) {
      return true;
    }
    if (qKey && (
      s.keywords.some(k => k.toLowerCase().includes(qKey) || qKey.includes(k.toLowerCase())) ||
      s.book.toLowerCase().includes(qKey) ||
      s.reference.toLowerCase().includes(qKey)
    )) {
      return true;
    }
    return false;
  });

  if (matches.length > 0) {
    const match = matches[Math.floor(Math.random() * matches.length)];
    return {
      verse: match.verse,
      reference: match.reference,
      book: match.book,
      theme: match.theme,
      canonical: true
    };
  }

  // 2. Pick a random verified scripture
  const random = VERIFIED_SCRIPTURES[Math.floor(Math.random() * VERIFIED_SCRIPTURES.length)];
  return {
    verse: random.verse,
    reference: random.reference,
    book: random.book,
    theme: random.theme,
    canonical: true
  };
}

/**
 * Validates and standardizes a scripture reference string into strict Ge'ez numerals.
 * e.g., "ማቴዎስ 5:8" -> "ማቴዎስ ፭፥፰"
 */
export function sanitizeReference(refStr = '') {
  if (!refStr) return '';

  let sanitized = refStr.trim();
  // Standardize separator to Ge'ez colon
  sanitized = sanitized.replace(/[:፡]/g, '፥');

  // Convert Arabic numerals into Ge'ez numerals
  sanitized = sanitized.replace(/\d+/g, (num) => {
    return toGeezNumerals(parseInt(num, 10));
  });

  return sanitized;
}

/**
 * Searches the canonical verses repository by query across text, book, theme, and keywords.
 */
export function searchCanonicalVerses(query = '') {
  if (!query) return VERIFIED_SCRIPTURES;
  const q = query.toLowerCase().trim();
  return VERIFIED_SCRIPTURES.filter(s => 
    s.verse.includes(q) ||
    s.reference.includes(q) ||
    s.book.includes(q) ||
    s.theme.toLowerCase().includes(q) ||
    s.keywords.some(k => k.toLowerCase().includes(q))
  );
}

/**
 * Returns all verses from a specific book or testament.
 */
export function getVersesByBook(bookName = '') {
  if (!bookName) return [];
  const b = bookName.trim();
  return VERIFIED_SCRIPTURES.filter(s => s.book.includes(b));
}

export function getTotalCanonicalCount() {
  return VERIFIED_SCRIPTURES.length;
}
